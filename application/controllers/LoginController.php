	function sentRecoverPassword()
	{


		if (!is_null($this->input->post_get("email_id"))) {
			$password = rand(100, 1000);
			$this->load->model("Global_model");
			$this->load->model("UserModel");
			$email = $this->input->post_get("email_id");
			$user_details = $this->UserModel->getUserByEmail($this->input->post_get("email_id"));
			if (!is_null($user_details)) {
				if ($this->UserModel->update_user(array("password" => $password), '', $user_details->user_id, $email)) {
//                    $this->Global_model->sendSms($user_details->mobile_no, "Welcome $user_details->user_name is successfully generated, Password is $password");
					$this->Global_model->sendEmail($user_details->email, "RMT New Password", "Welcome $user_details->user_name is successfully generated, Password is $password");
					$response["status"] = 200;
					$response["body"] = "New Password sent to registered email and Mobile number";
				} else {
					$response["status"] = 202;
					$response["body"] = "Something went to wrong";
				}
			} else {
				$response["status"] = 202;
				$response["body"] = "User Not Found";
			}
		} else {
			$response["status"] = 201;
			$response["body"] = "Invalid Parameter";
		}
		echo json_encode($response);
	}

